CREATE OR REPLACE FUNCTION public.event_key_lookup(p_source text, p_source_event_id bigint)
 RETURNS bigint
 LANGUAGE sql
 STABLE
 SET search_path TO 'public', 'pg_temp'
AS $function$
  SELECT x.xmap_id FROM public.event_xmap x
   WHERE CASE lower(trim(coalesce(p_source, '')))
           WHEN 'tevo' THEN x.tevo_event_id WHEN 'evo' THEN x.tevo_event_id
           WHEN 'tickpick' THEN x.tp_event_id WHEN 'tp' THEN x.tp_event_id
           WHEN 'vivid' THEN x.vivid_event_id WHEN 'vividseats' THEN x.vivid_event_id
           WHEN 'gotickets' THEN x.gt_event_id WHEN 'gt' THEN x.gt_event_id
           WHEN 'axs' THEN x.axs_event_id
           WHEN 'seatgeek' THEN x.sg_event_id WHEN 'sg' THEN x.sg_event_id
           WHEN 'mlb' THEN x.mlb_schedule_id
           WHEN 'espn' THEN x.espn_event_id
           WHEN 'tm' THEN x.tm_event_seq WHEN 'ticketmaster' THEN x.tm_event_seq
           WHEN 'primary' THEN x.pp_event_seq END = p_source_event_id
   LIMIT 1
$function$;
COMMENT ON FUNCTION public.event_key_lookup(text, bigint) IS 'The internal event key for a source''s listing id (tevo | tickpick | vivid | gotickets | axs | seatgeek | mlb | espn | tm — tm_discovery_event.tm_seq | primary — primary_poll_event.pp_seq; a box office''s own id goes through event_key_lookup_primary). Migs 20261117170000 / 190000 / 20261123190000.';
CREATE OR REPLACE FUNCTION public.event_key_lookup_primary(p_source text, p_source_event_id text)
 RETURNS bigint
 LANGUAGE sql
 STABLE
 SET search_path TO 'public', 'pg_temp'
AS $function$
  SELECT x.xmap_id FROM public.primary_poll_event p JOIN public.event_xmap x ON x.pp_event_seq = p.pp_seq
   WHERE p.source = p_source AND p.source_event_id = p_source_event_id LIMIT 1
$function$;
REVOKE ALL ON FUNCTION public.event_key_lookup(text, bigint), public.event_key_lookup_primary(text, text), public.primary_poll_map(boolean) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.event_key_lookup(text, bigint), public.event_key_lookup_primary(text, text), public.primary_poll_map(boolean) TO service_role;
REVOKE ALL ON public.primary_poll_map_audit FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.primary_poll_map_audit TO service_role;

