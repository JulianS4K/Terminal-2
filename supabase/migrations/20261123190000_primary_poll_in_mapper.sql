CREATE OR REPLACE FUNCTION public.primary_poll_map(p_apply boolean DEFAULT true)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions', 'pg_temp'
 SET client_min_messages TO 'warning'
AS $function$
DECLARE
  v_run uuid := gen_random_uuid();
  v_out jsonb := '{}'::jsonb;
  v_n   int;
BEGIN
  IF NOT pg_try_advisory_xact_lock(hashtext('primary_poll_map')) THEN
    RETURN jsonb_build_object('skipped', 'another primary_poll_map is running');
  END IF;

  -- 0. the rows: upcoming, at a venue we know, not a series / membership / season / deposit entry
  DROP TABLE IF EXISTS _pp_cand;
  CREATE TEMP TABLE _pp_cand ON COMMIT DROP AS
  SELECT p.source, p.source_event_id, p.name, p.event_date, p.start_local_time, b.tevo_venue_id,
         p.tevo_event_id AS cur_tevo, p.tevo_match_method AS cur_method,
         public.event_mapper_norm_name(p.name) ~ '\mpass\M' AS is_pass
    FROM public.primary_poll_event p
    JOIN public.venue_primary_box_office b ON b.source = p.source
   WHERE p.event_date BETWEEN current_date - 1 AND current_date + 400
     AND coalesce(p.name, '') <> '' AND p.name !~* '(series|membership|member|season|deposit)';
  v_out := v_out || jsonb_build_object('candidates', (SELECT count(*) FROM _pp_cand));

  -- 1. verify the matched: still that event, at that venue, on that day?
  DROP TABLE IF EXISTS _pp_drop;
  CREATE TEMP TABLE _pp_drop ON COMMIT DROP AS
  SELECT c.source, c.source_event_id, c.cur_tevo, c.cur_method,
         CASE WHEN e.id IS NULL THEN 'event_gone' WHEN e.state = 'ignored' THEN 'event_ignored'
              WHEN e.venue_id IS DISTINCT FROM c.tevo_venue_id THEN 'venue_moved' ELSE 'day_moved' END AS why
    FROM _pp_cand c LEFT JOIN public.events e ON e.id = c.cur_tevo
   WHERE c.cur_tevo IS NOT NULL
     AND (e.id IS NULL OR e.state = 'ignored' OR e.venue_id IS DISTINCT FROM c.tevo_venue_id
          OR left(e.occurs_at_local, 10) IS DISTINCT FROM to_char(c.event_date, 'YYYY-MM-DD'));
  v_out := v_out || jsonb_build_object('dropped', (SELECT count(*) FROM _pp_drop));
  IF p_apply THEN
    INSERT INTO public.primary_poll_map_audit (run_id, source, source_event_id, action, tevo_event_id, method, note)
    SELECT v_run, d.source, d.source_event_id, 'drop', d.cur_tevo, d.cur_method, d.why FROM _pp_drop d;
    UPDATE public.primary_poll_event p SET tevo_event_id = NULL, tevo_match_method = NULL, tevo_matched_at = NULL
      FROM _pp_drop d WHERE d.source = p.source AND d.source_event_id = p.source_event_id;
  END IF;
  UPDATE _pp_cand c SET cur_tevo = NULL, cur_method = NULL FROM _pp_drop d WHERE d.source = c.source AND d.source_event_id = c.source_event_id;

  -- 2. the EVO events at the venue on the day, products left out; a pass / package only against a pass / package
  DROP TABLE IF EXISTS _pp_fit;
  CREATE TEMP TABLE _pp_fit ON COMMIT DROP AS
  SELECT c.source, c.source_event_id, e.id AS tevo_event_id, e.name AS evo_name,
         public.xmap_name_fits(c.name, NULL, e.name, CASE WHEN e.primary_performer_name IS NOT NULL THEN ARRAY[e.primary_performer_name] END) AS name_fits
    FROM _pp_cand c
    JOIN public.events e ON e.venue_id = c.tevo_venue_id AND e.state IS DISTINCT FROM 'ignored'
                        AND left(e.occurs_at_local, 10) = to_char(c.event_date, 'YYYY-MM-DD')
   WHERE c.cur_tevo IS NULL
     AND e.name !~* '(parking|tailgate|shuttle|hospitality|\mvip\M|suites?\M)'
     AND (public.event_mapper_norm_name(e.name) ~ '\m(pass|package)\M') = c.is_pass
     AND NOT (c.start_local_time IS NOT NULL AND e.occurs_at_local ~ 'T\d\d:\d\d' AND e.occurs_at_local !~ 'T(00:00|23:59|03:30)'
              AND abs(extract(epoch FROM (c.event_date + c.start_local_time) - left(e.occurs_at_local, 16)::timestamp)) > 3 * 3600);
  DROP TABLE IF EXISTS _pp_pick;
  CREATE TEMP TABLE _pp_pick ON COMMIT DROP AS
  WITH per AS (
    SELECT f.source, f.source_event_id, count(*) AS n, count(*) FILTER (WHERE f.name_fits) AS n_fit,
           min(f.tevo_event_id) AS one, min(f.tevo_event_id) FILTER (WHERE f.name_fits) AS one_fit,
           min(f.evo_name) AS one_name, min(f.evo_name) FILTER (WHERE f.name_fits) AS one_fit_name
      FROM _pp_fit f GROUP BY f.source, f.source_event_id)
  SELECT p.source, p.source_event_id,
         CASE WHEN p.n_fit = 1 THEN p.one_fit WHEN p.n = 1 THEN p.one END AS tevo_event_id,
         CASE WHEN p.n_fit = 1 THEN 'venue_date_name' WHEN p.n = 1 THEN 'venue_date_only' END AS method,
         CASE WHEN p.n_fit = 1 THEN p.one_fit_name WHEN p.n = 1 THEN p.one_name END AS evo_name,
         p.n AS candidates, p.n_fit AS fitting
    FROM per p;
  v_out := v_out || jsonb_build_object(
    'matched', (SELECT count(*) FROM _pp_pick WHERE tevo_event_id IS NOT NULL),
    'by_method', (SELECT coalesce(jsonb_object_agg(method, n), '{}'::jsonb) FROM (SELECT method, count(*) n FROM _pp_pick WHERE tevo_event_id IS NOT NULL GROUP BY 1) s),
    'ambiguous', (SELECT count(*) FROM _pp_pick WHERE tevo_event_id IS NULL),
    'no_candidate', (SELECT count(*) FROM _pp_cand c WHERE c.cur_tevo IS NULL AND NOT EXISTS (SELECT 1 FROM _pp_pick k WHERE k.source = c.source AND k.source_event_id = c.source_event_id)),
    'already_matched', (SELECT count(*) FROM _pp_cand WHERE cur_tevo IS NOT NULL),
    'sample', (SELECT coalesce(jsonb_agg(c.name || ' => ' || k.evo_name || ' [' || k.method || ']'), '[]'::jsonb)
                 FROM (SELECT * FROM _pp_pick WHERE tevo_event_id IS NOT NULL ORDER BY source, source_event_id LIMIT 12) k JOIN _pp_cand c ON c.source = k.source AND c.source_event_id = k.source_event_id));

  -- 3. apply: fill-only, audited
  IF p_apply THEN
    WITH upd AS (
      UPDATE public.primary_poll_event p SET tevo_event_id = k.tevo_event_id, tevo_match_method = k.method, tevo_matched_at = now()
        FROM _pp_pick k WHERE k.tevo_event_id IS NOT NULL AND p.source = k.source AND p.source_event_id = k.source_event_id AND p.tevo_event_id IS NULL
      RETURNING p.source, p.source_event_id, p.tevo_event_id, p.tevo_match_method)
    INSERT INTO public.primary_poll_map_audit (run_id, source, source_event_id, action, tevo_event_id, method, note)
    SELECT v_run, u.source, u.source_event_id, 'match', u.tevo_event_id, u.tevo_match_method, k.evo_name
      FROM upd u JOIN _pp_pick k ON k.source = u.source AND k.source_event_id = u.source_event_id;
    GET DIAGNOSTICS v_n = ROW_COUNT;
    v_out := v_out || jsonb_build_object('written', v_n);
  END IF;
  RETURN jsonb_build_object('run_id', v_run, 'applied', p_apply) || v_out;
END $function$;
COMMENT ON FUNCTION public.primary_poll_map(boolean) IS 'Maps primary_poll_event rows (the box offices we poll) to EVO events: the source''s own venue (venue_primary_box_office), the same local day, products left out, pass/package only against pass/package; one candidate whose name fits, else the one event of the day; starts more than 3 h apart never pair. Fill-only, audited; a stale match is cleared first. Mig 20261123190000.';

