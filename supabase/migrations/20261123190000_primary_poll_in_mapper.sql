CREATE OR REPLACE FUNCTION public.event_xmap_tick(p_days integer DEFAULT 45, p_apply boolean DEFAULT true)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions', 'pg_temp'
 SET client_min_messages TO 'warning'
AS $function$
DECLARE
  v_run   uuid := gen_random_uuid();
  v_out   jsonb := '{}'::jsonb;
  v_n     int;
  v_from  date := current_date - 1;
  v_to    date := current_date + coalesce(p_days, 45);
  v_srcs  constant text[] := ARRAY['mlb', 'tickpick', 'vivid', 'sg', 'gotickets', 'axs', 'espn', 'tm', 'primary'];
  v_cols  constant text[] := ARRAY['mlb_schedule_id', 'tp_event_id', 'vivid_event_id', 'sg_event_id', 'gt_event_id', 'axs_event_id', 'espn_event_id', 'tm_event_seq', 'pp_event_seq'];
  i       int;
  v_t     timestamptz := clock_timestamp();
  v_ms    jsonb := '{}'::jsonb;
BEGIN
  -- one run at a time: the hourly cron must not start while a nightly or a by-hand run is still clustering
  IF NOT pg_try_advisory_xact_lock(hashtext('event_xmap')) THEN
    RETURN jsonb_build_object('skipped', 'another event_xmap_tick is running');
  END IF;
  INSERT INTO public.event_xmap_run (run_id, days, applied) VALUES (v_run, p_days, p_apply);

  -- 0. the working set: every source's rows in the window, normalised
  DROP TABLE IF EXISTS _xm_tv;
  CREATE TEMP TABLE _xm_tv ON COMMIT DROP AS SELECT * FROM public.catalog_tevo_venues_by_name();
  CREATE INDEX ON _xm_tv (nm, st);

  DROP TABLE IF EXISTS _xm_ev;
  CREATE TEMP TABLE _xm_ev (
    src text, sid bigint, pri int, venue_key text, tevo_venue_id bigint, local_day date, start_local timestamp,
    name text, perfs text[], tevo_event_id bigint, venue_name text, city text, state text) ON COMMIT DROP;

  -- MLB schedule (games): venue through the park xref; the start MLB publishes unless TBD
  INSERT INTO _xm_ev
  SELECT 'mlb', g.schedule_id, 1, 'tv:' || x.tevo_venue_id, x.tevo_venue_id, g.game_date,
         CASE WHEN NOT coalesce(g.is_tbd, false) THEN g.game_time_local END,
         g.away_name || ' at ' || g.home_name, ARRAY[g.away_name, g.home_name], g.tevo_event_id, g.venue_name, g.venue_city, NULL
    FROM public.mlb_ticket_game g
    JOIN public.mlb_venue_xref x ON x.mlb_venue_id = g.venue_id AND x.tevo_venue_id IS NOT NULL
   WHERE g.removed_at IS NULL AND g.game_date BETWEEN v_from AND v_to AND g.away_name IS NOT NULL AND g.home_name IS NOT NULL;

  -- ESPN games (mig 20261117170000): the venue through the Vivid venue ESPN links to, when paired, else name + state;
  -- the start when ESPN has the time; the sides as performers. The most structured source: it seeds its bucket.
  INSERT INTO _xm_ev
  SELECT 'espn', g.espn_event_id::bigint, 0,
         CASE WHEN v.tevo_venue_id IS NOT NULL THEN 'tv:' || v.tevo_venue_id ELSE 'ns:' || lower(trim(g.venue_name)) || '|' || upper(trim(coalesce(g.venue_state, ''))) END,
         v.tevo_venue_id,
         (g.game_at_utc AT TIME ZONE coalesce(tz.iana_tz, public.xmap_state_tz(g.venue_state, 'US')))::date,
         CASE WHEN coalesce(g.time_valid, true) THEN (g.game_at_utc AT TIME ZONE coalesce(tz.iana_tz, public.xmap_state_tz(g.venue_state, 'US')))::timestamp END,
         g.name, ARRAY[g.away_name, g.home_name], g.tevo_event_id, g.venue_name, g.venue_city, g.venue_state
    FROM public.espn_ticket_game g
    LEFT JOIN public.vivid_catalog_venue v ON v.vivid_venue_id = g.vivid_venue_id AND v.tevo_venue_id IS NOT NULL
    LEFT JOIN public.venue_timezone tz ON tz.tevo_venue_id = v.tevo_venue_id
   WHERE g.espn_event_id ~ '^\d+$' AND g.game_at_utc IS NOT NULL
     AND g.game_at_utc BETWEEN (v_from::timestamp AT TIME ZONE 'UTC') - interval '1 day' AND (v_to::timestamp AT TIME ZONE 'UTC') + interval '1 day'
     AND coalesce(g.status, '') NOT IN ('STATUS_FINAL', 'STATUS_CANCELED', 'STATUS_POSTPONED')
     AND coalesce(g.home_team_id, '0') <> '-1' AND coalesce(g.away_team_id, '0') <> '-1'
     AND coalesce(g.home_name, '') <> '' AND coalesce(g.away_name, '') <> '' AND coalesce(g.venue_name, '') <> '';
  DELETE FROM _xm_ev WHERE src = 'espn' AND (local_day < v_from OR local_day > v_to);

  -- Primary box offices we poll ourselves (mig 20261123190000): the venue is the source's own (venue_primary_box_office),
  -- the start as the box office gives it. The most authoritative source there is: it seeds its bucket before ESPN.
  INSERT INTO _xm_ev
  SELECT 'primary', p.pp_seq, -1, 'tv:' || b.tevo_venue_id, b.tevo_venue_id, p.event_date,
         CASE WHEN p.start_local_time IS NOT NULL THEN p.event_date + p.start_local_time END,
         p.name, NULL, p.tevo_event_id, p.venue_name, p.venue_city, p.venue_state
    FROM public.primary_poll_event p
    JOIN public.venue_primary_box_office b ON b.source = p.source
   WHERE p.event_date BETWEEN v_from AND v_to AND coalesce(p.name, '') <> ''
     AND p.name !~* '(series|membership|member|season|deposit)';

  -- Ticketmaster (mig 20261117190000): the box office's own catalogue; its string id travels as tm_discovery_event.tm_seq.
  -- The venue through tm_venue_xref when paired, else name + state; the local date and time as TM gives them.
  INSERT INTO _xm_ev
  SELECT 'tm', d.tm_seq, 2,
         CASE WHEN x.tevo_venue_id IS NOT NULL THEN 'tv:' || x.tevo_venue_id ELSE 'ns:' || lower(trim(d.venue_name)) || '|' || upper(trim(coalesce(d.venue_state, ''))) END,
         x.tevo_venue_id, d.local_date,
         CASE WHEN NOT coalesce(d.time_tba, false) AND d.local_time IS NOT NULL THEN d.local_date + d.local_time END,
         d.name, d.attraction_names, d.tevo_event_id, d.venue_name, d.venue_city, d.venue_state
    FROM public.tm_discovery_event d
    LEFT JOIN public.tm_venue_xref x ON x.tm_venue_id = d.tm_venue_id AND x.tevo_venue_id IS NOT NULL
   WHERE d.local_date BETWEEN v_from AND v_to AND NOT d.is_product AND NOT coalesce(d.date_tbd, false)
     AND coalesce(d.status_code, 'onsale') NOT IN ('cancelled', 'canceled')
     AND coalesce(d.venue_country, 'US') IN ('US', 'CA', 'MX') AND coalesce(d.venue_name, '') <> '';

  -- TickPick
  INSERT INTO _xm_ev
  SELECT 'tickpick', c.tp_event_id, 3,
         CASE WHEN v.tevo_venue_id IS NOT NULL THEN 'tv:' || v.tevo_venue_id ELSE 'ns:' || lower(trim(v.name)) || '|' || upper(trim(coalesce(v.state, ''))) END,
         v.tevo_venue_id, c.event_date, CASE WHEN c.time_confirmed THEN c.event_local END,
         c.name, (SELECT array_agg(p->>'name') FROM jsonb_array_elements(coalesce(c.performers, '[]'::jsonb)) p WHERE coalesce(p->>'name', '') <> ''),
         c.tevo_event_id, v.name, v.city, v.state
    FROM public.tickpick_catalog_event c
    JOIN public.tickpick_catalog_venue v ON v.tp_venue_id = c.tp_venue_id
   WHERE c.date_confirmed AND c.status IS DISTINCT FROM 'canceled' AND c.merged_into IS NULL
     AND c.event_date BETWEEN v_from AND v_to AND coalesce(c.venue_country, 'US') IN ('US', 'CA', 'MX')
     AND coalesce(v.name, '') <> '';

  -- Vivid Seats
  INSERT INTO _xm_ev
  SELECT 'vivid', c.vivid_event_id, 4,
         CASE WHEN v.tevo_venue_id IS NOT NULL THEN 'tv:' || v.tevo_venue_id ELSE 'ns:' || lower(trim(v.name)) || '|' || upper(trim(coalesce(v.state, ''))) END,
         v.tevo_venue_id, c.event_date, CASE WHEN c.time_known THEN c.event_local END,
         c.name, (SELECT array_agg(coalesce(p->>'name', p#>>'{}')) FROM jsonb_array_elements(coalesce(c.performers, '[]'::jsonb)) p WHERE coalesce(p->>'name', p#>>'{}', '') <> ''),
         c.tevo_event_id, v.name, v.city, v.state
    FROM public.vivid_catalog_event c
    JOIN public.vivid_catalog_venue v ON v.vivid_venue_id = c.vivid_venue_id
   WHERE c.event_date BETWEEN v_from AND v_to AND coalesce(c.venue_country, 'US') IN ('US', 'CA', 'MX')
     AND coalesce(v.name, '') <> '';

  -- SeatGeek canonical: venue through aq_venue_map / cross_source_venue_map, else name + state
  INSERT INTO _xm_ev
  SELECT 'sg', s.sg_event_id, 5,
         CASE WHEN tv.tevo_venue_id IS NOT NULL THEN 'tv:' || tv.tevo_venue_id ELSE 'ns:' || lower(trim(s.sg_venue_name)) || '|' || upper(trim(coalesce(s.sg_venue_state, ''))) END,
