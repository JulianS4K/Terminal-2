-- 2. Replace: clear existing zones for every in-scope (performer,venue) pair.
--    performer_zone_rules cascades on the zone delete.
DELETE FROM performer_zones pz
USING (SELECT DISTINCT performer_id, venue_id FROM _zap_stage_zone) s
WHERE pz.performer_id = s.performer_id
  AND pz.venue_id     = s.venue_id;

-- 3. Insert zones (fresh serial ids), capture ext_id -> new id via the unique
--    (performer_id, venue_id, name) key.
CREATE TEMP TABLE _zap_idmap (ext_id int PRIMARY KEY, new_id bigint NOT NULL) ON COMMIT DROP;

WITH ins AS (
  INSERT INTO performer_zones (performer_id, venue_id, name, display_order, source)
  SELECT performer_id, venue_id, name, display_order, 'curated'
  FROM _zap_stage_zone
  RETURNING id, performer_id, venue_id, name
)
INSERT INTO _zap_idmap (ext_id, new_id)
SELECT s.ext_id, ins.id
FROM ins
JOIN _zap_stage_zone s
  ON s.performer_id = ins.performer_id
 AND s.venue_id     = ins.venue_id
 AND s.name         = ins.name;

-- 4. Insert the section/row rules against the new zone ids.
INSERT INTO performer_zone_rules (zone_id, section_from, section_to, row_from, row_to)
SELECT m.new_id, r.section_from, r.section_to, r.row_from, r.row_to
FROM _zap_stage_rule r
JOIN _zap_idmap m ON m.ext_id = r.ext_zone_id;

-- 5. Fail loudly if anything did not land 1:1.
DO $$
DECLARE want_z int; want_r int; got_map int; got_z int; got_r int;
BEGIN
  SELECT count(*) INTO want_z FROM _zap_stage_zone;
  SELECT count(*) INTO want_r FROM _zap_stage_rule;
  SELECT count(*) INTO got_map FROM _zap_idmap;
  SELECT count(*) INTO got_z FROM performer_zones
    WHERE (performer_id, venue_id) IN (SELECT DISTINCT performer_id, venue_id FROM _zap_stage_zone)
      AND source = 'curated';
  SELECT count(*) INTO got_r FROM performer_zone_rules r
    JOIN performer_zones z ON z.id = r.zone_id
    WHERE (z.performer_id, z.venue_id) IN (SELECT DISTINCT performer_id, venue_id FROM _zap_stage_zone);
  IF got_map <> want_z THEN
    RAISE EXCEPTION 'zap import: id-map count %/% (natural-key join lost rows)', got_map, want_z; END IF;
  IF got_z <> want_z THEN
    RAISE EXCEPTION 'zap import: inserted % zones, expected %', got_z, want_z; END IF;
  IF got_r <> want_r THEN
    RAISE EXCEPTION 'zap import: inserted % rules, expected %', got_r, want_r; END IF;
  RAISE NOTICE 'zap import OK: % zones, % rules across % pairs', got_z, got_r,
    (SELECT count(DISTINCT (performer_id,venue_id)) FROM _zap_stage_zone);
END $$;
